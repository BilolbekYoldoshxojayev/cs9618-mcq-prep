def generated():
    rng = random.Random(202)
    out = []
    ip = "IP, URL and DNS"
    # valid IPv4 address
    for k in range(2):
        a = [rng.choice([10, 172, 192, 45, 88, 203]), rng.randint(0, 255), rng.randint(0, 255), rng.randint(1, 254)]
        c = ".".join(map(str, a))
        bad = [".".join(map(str, a[:3])),
               ".".join(map(str, a[:3] + [rng.randint(256, 400)])),
               ".".join(map(str, a + [rng.randint(1, 200)]))]
        stem = ["Which of the following is a valid IPv4 address?",
                "A network technician types in one address for a device. Which is a valid IPv4 address?"][k]
        out.append(Q(CH, ip, 1, stem, c, bad,
                     "IPv4 addresses have four denary numbers from 0 to 255 separated by full stops."))
    return out
